#!/usr/bin/env python3
"""Assemble the static AIK tutorial from committed synthetic evidence."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SHOWCASE_SOURCE = ROOT / "showcase"
CASE_SOURCE = ROOT / "examples" / "langgraph-multi-agent" / "case"
HISTORY_SOURCE = ROOT / "examples" / "langgraph-multi-agent" / "history-demo" / "aik-history"
BUILD_MARKER = ".aik-showcase-build"


def build(output: str | Path) -> Path:
    destination = Path(output).resolve()
    unsafe_destinations = {ROOT.resolve(), SHOWCASE_SOURCE.resolve(), (ROOT / "examples").resolve(), (ROOT / "docs").resolve()}
    if destination in unsafe_destinations:
        raise ValueError(f"Refusing unsafe showcase output path: {destination}")

    required = [
        SHOWCASE_SOURCE / "index.html",
        SHOWCASE_SOURCE / "style.css",
        SHOWCASE_SOURCE / "assets" / "screenshots" / "01-overview.png",
        SHOWCASE_SOURCE / "assets" / "screenshots" / "02-before-after-review.png",
        SHOWCASE_SOURCE / "assets" / "screenshots" / "03-case-evidence.png",
        SHOWCASE_SOURCE / "assets" / "screenshots" / "04-reliability.png",
        SHOWCASE_SOURCE / "assets" / "screenshots" / "05-history-dashboard.png",
        CASE_SOURCE / "review.html",
        CASE_SOURCE / "comparison.json",
        CASE_SOURCE / "test_cases.jsonl",
        HISTORY_SOURCE / "dashboard.html",
    ]
    missing = [str(path.relative_to(ROOT)) for path in required if not path.exists()]
    if missing:
        raise FileNotFoundError("Missing showcase input(s): " + ", ".join(missing))

    if destination.exists() and not destination.is_dir():
        raise ValueError(f"Showcase output exists and is not a directory: {destination}")
    if destination.exists() and not (destination / BUILD_MARKER).is_file():
        raise ValueError(f"Refusing to replace an unmarked directory: {destination}")
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(SHOWCASE_SOURCE, destination)

    demo = destination / "demo"
    demo.mkdir()
    shutil.copy2(CASE_SOURCE / "review.html", demo / "review.html")
    shutil.copy2(CASE_SOURCE / "comparison.json", demo / "comparison.json")
    shutil.copy2(CASE_SOURCE / "test_cases.jsonl", demo / "test_cases.jsonl")
    shutil.copytree(HISTORY_SOURCE, demo / "history")
    (destination / ".nojekyll").write_text("", encoding="utf-8")
    (destination / BUILD_MARKER).write_text("generated by AIK\n", encoding="utf-8")

    forbidden = str(ROOT.resolve()).lower()
    leaked = []
    for path in destination.rglob("*"):
        if path.is_file() and path.suffix.lower() in {".html", ".json", ".jsonl", ".css", ".md"}:
            if forbidden in path.read_text(encoding="utf-8").lower():
                leaked.append(str(path.relative_to(destination)))
    if leaked:
        raise ValueError("Showcase contains an absolute workspace path: " + ", ".join(leaked))
    return destination


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the static AIK showcase")
    parser.add_argument("--output", default=ROOT / "dist" / "showcase")
    args = parser.parse_args()
    destination = build(args.output)
    print(destination)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
